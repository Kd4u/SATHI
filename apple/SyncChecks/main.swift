import Foundation
func snapshot(_ values: [String: String]) -> SyncSnapshot { SyncSnapshot(records: values.mapValues { Data($0.utf8) }) }
let base = snapshot(["a":"old", "b":"old"])
let merged = try SyncSnapshot.merge(base: base, local: snapshot(["a":"new", "b":"old"]), remote: snapshot(["a":"old", "b":"remote"]))
assert(merged == snapshot(["a":"new", "b":"remote"]))
assert(try! SyncSnapshot.merge(base: base, local: snapshot(["b":"old"]), remote: base) == snapshot(["b":"old"]))
do { _ = try SyncSnapshot.merge(base: base, local: snapshot(["a":"local", "b":"old"]), remote: snapshot(["a":"remote", "b":"old"])); fatalError("Conflict was overwritten") } catch SyncFailure.conflict { }
do { _ = try SyncSnapshot.merge(base: base, local: snapshot(["b":"old"]), remote: snapshot(["a":"remote", "b":"old"])); fatalError("Delete conflict was overwritten") } catch SyncFailure.conflict { }
assert(try! SyncSnapshot.merge(base: .init(), local: .init(), remote: base) == base)
assert(try! SyncSnapshot.merge(base: base, local: base, remote: .init()) == .init())
print("Sync merge checks passed: independent edits, deletions, conflicts, empty device, remote deletion.")

let jsonBase = snapshot(["timetable": "{\"a\":1,\"b\":2}"])
let reordered = snapshot(["timetable": "{\"b\":2,\"a\":1}"])
let jsonRemote = snapshot(["timetable": "{\"a\":1,\"b\":3}"])
assert(try! SyncSnapshot.merge(base: jsonBase, local: reordered, remote: jsonRemote) == jsonRemote)
assert(try! SyncSnapshot.merge(base: .init(), local: jsonBase, remote: reordered) == jsonBase)
print("Cross-client JSON order checks passed; real conflicts remain protected.")

let conflictsBase = snapshot(["a":"old", "b":"old", "c":"old"])
let conflictsLocal = snapshot(["a":"mine", "b":"old", "c":"local"])
let conflictsRemote = snapshot(["a":"cloud", "b":"remote", "c":"old"])
assert(try! SyncSnapshot.merge(base: conflictsBase, local: conflictsLocal, remote: conflictsRemote, resolving: .local) == snapshot(["a":"mine", "b":"remote", "c":"local"]))
assert(try! SyncSnapshot.merge(base: conflictsBase, local: conflictsLocal, remote: conflictsRemote, resolving: .remote) == snapshot(["a":"cloud", "b":"remote", "c":"local"]))
print("Explicit conflict choice preserves independent edits on both devices.")

let bundledBase = snapshot(["timetable":"old", "selection":"old subjects", "attendance:1":"old"])
let bundledLocal = snapshot(["timetable":"mine", "selection":"my subjects", "attendance:1":"old"])
let bundledRemote = snapshot(["timetable":"cloud", "selection":"old subjects", "attendance:1":"remote mark"])
let bundleChoice = try SyncSnapshot.merge(base: bundledBase, local: bundledLocal, remote: bundledRemote, resolving: .remote)
assert(bundleChoice == bundledRemote)
print("Timetable conflict selection stays aligned with its semester/subjects.")

let stuckBase = snapshot(["timetable":"old", "selection":"subjects", "attendance:class1":"Unmarked"])
let phoneOD = snapshot(["timetable":"phone draft", "selection":"subjects", "attendance:class1":"OD"])
let macSchedule = snapshot(["timetable":"correct Mac", "selection":"subjects", "attendance:class1":"Unmarked"])
let partial = try SyncExchange.prepare(base: stuckBase, local: phoneOD, remote: macSchedule)
assert(partial.cloud.records["attendance:class1"] == Data("OD".utf8))
assert(partial.cloud.records["timetable"] == macSchedule.records["timetable"])
assert(partial.local.records["timetable"] == phoneOD.records["timetable"])
assert(partial.checkpoint.records["timetable"] == stuckBase.records["timetable"])
let repeatPartial = try SyncExchange.prepare(base: partial.checkpoint, local: partial.local, remote: partial.cloud)
assert(repeatPartial.cloud == partial.cloud && repeatPartial.local == partial.local)
let resolvedPartial = try SyncExchange.prepare(base: partial.checkpoint, local: partial.local, remote: partial.cloud, resolving: .remote)
assert(resolvedPartial.local.records["attendance:class1"] == Data("OD".utf8))
assert(resolvedPartial.local.records["timetable"] == macSchedule.records["timetable"])
let receiving = try SyncExchange.prepare(base: macSchedule, local: macSchedule, remote: partial.cloud)
assert(receiving.local.records["attendance:class1"] == Data("OD".utf8))
print("OD crosses devices despite an unrelated timetable conflict; drafts/checkpoints survive retries and resolution.")

func tableRecord(_ ids: [String], revision: Int = 0) throws -> Data {
    try JSONSerialization.data(withJSONObject: ["importRevision":revision, "sessions": ids.map { ["id":$0,"date":"2026-11-01","time":"09:00-10:30","subject":"Course","section":"A","source":"Sheet1!"+$0] }])
}
let oldTable = try tableRecord(["C2"]), completeTable = try tableRecord(["C2", "J2"], revision: 2)
let completeLocal = SyncSnapshot(records: ["timetable":completeTable])
let incompleteRemote = SyncSnapshot(records: ["timetable":oldTable])
let noDowngrade = try SyncExchange.prepare(base: .init(), local: completeLocal, remote: incompleteRemote)
assert(noDowngrade.cloud == completeLocal && noDowngrade.local == completeLocal && noDowngrade.conflicts.isEmpty)
let receiveRepair = try SyncExchange.prepare(base: incompleteRemote, local: incompleteRemote, remote: completeLocal)
assert(receiveRepair.local == completeLocal)
let differentTerm = try tableRecord(["D2"])
assert(SyncSnapshot.completeTimetable(oldTable, differentTerm) == nil)
print("Verified complete imports cannot regress to a matching partial cloud copy; different schedules remain distinct.")

let verifiedSmaller = try tableRecord(["C2"], revision: 2)
assert(SyncSnapshot.completeTimetable(verifiedSmaller, completeTable) == nil)
